from pathlib import Path

from psycopg import Connection, connect

from reader import gen_iterate


def prepare_table(conn: Connection):
    conn.execute("""
                 CREATE TABLE raw
                 (
                     id                          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                     local_id                    INTEGER       NOT NULL,
                     unit                        INTEGER       NOT NULL,
                     strategy                    strategy_kind NOT NULL,
                     total_payed                 money         NOT NULL,
                     first_cnt                   INTEGER       NOT NULL,
                     first_prize                 money         NOT NULL,
                     first_adjacent_cnt          INTEGER       NOT NULL,
                     first_adjacent_prize        money         NOT NULL,
                     first_different_group_cnt   INTEGER       NOT NULL,
                     first_different_group_prize money         NOT NULL,
                     second_cnt                  INTEGER       NOT NULL,
                     second_prize                money         NOT NULL,
                     third_cnt                   INTEGER       NOT NULL,
                     third_prize                 money         NOT NULL,
                     fourth_cnt                  INTEGER       NOT NULL,
                     fourth_prize                money         NOT NULL,
                     fifth_cnt                   INTEGER       NOT NULL,
                     fifth_prize                 money         NOT NULL,
                     sixth_cnt                   INTEGER       NOT NULL,
                     sixth_prize                 money         NOT NULL,
                     seventh_cnt                 INTEGER       NOT NULL,
                     seventh_prize               money         NOT NULL
                 );
                 """)


def insert_raw(conn: Connection, path: Path, unit: int):
    with conn.cursor() as cur:
        with cur.copy("""
                      COPY raw (local_id,
                                unit,
                                strategy,
                                total_payed,
                                first_cnt,
                                first_prize,
                                first_adjacent_cnt,
                                first_adjacent_prize,
                                first_different_group_cnt,
                                first_different_group_prize,
                                second_cnt,
                                second_prize,
                                third_cnt,
                                third_prize,
                                fourth_cnt,
                                fourth_prize,
                                fifth_cnt,
                                fifth_prize,
                                sixth_cnt,
                                sixth_prize,
                                seventh_cnt,
                                seventh_prize)
                          FROM STDIN;
                      """) as cpy:
            for idx, elem in enumerate(gen_iterate(path)):
                tmp = elem[0], unit, *elem[1:]
                if idx & 1023 == 0:
                    print(f"inserted {idx} rows")
                cpy.write_row(tmp)


